void SetView(Vector2 offset, float zoom)
{
    assert(zoom > 0.0f);
    Flush();
    g.viewOffset = offset;
    g.viewZoom   = zoom;
    UpdateProjection();
}

void Flush()
{
    if (g.vertCount == 0) { return; }
    assert(ValidTexture(g.batchTex));
    D3D11_MAPPED_SUBRESOURCE map {};
    if (FAILED(g.ctx->Map(g.vbuf.Get(), 0, D3D11_MAP_WRITE_DISCARD, 0, &map))) { g.vertCount = 0; return; }
    std::memcpy(map.pData, g.verts.data(), sizeof(Vertex) * static_cast<size_t>(g.vertCount));
    g.ctx->Unmap(g.vbuf.Get(), 0);

    const TextureSlot& t = Tex(g.batchTex);
    ID3D11ShaderResourceView* srv = t.srv.Get();
    ID3D11SamplerState* smp = g.samplers[static_cast<size_t>(t.filter)][static_cast<size_t>(t.wrap)].Get();
    g.ctx->PSSetShaderResources(0, 1, &srv);
    g.ctx->PSSetSamplers(0, 1, &smp);
    g.ctx->Draw(static_cast<UINT>(g.vertCount), 0);
    g.vertCount = 0;
}

void Quad(TextureId tex, Rectangle src, Rectangle dst, Vector2 origin, float rotationDeg, Color tint)
{
    if (!ValidTexture(tex)) { return; }
    const TextureSlot& t = Tex(tex);
    const float tw = static_cast<float>(t.w), th = static_cast<float>(t.h);

    // Negative source extents flip that axis (raylib semantics).
    const bool  flipX = src.width < 0.0f, flipY = src.height < 0.0f;
    const float sw = std::fabs(src.width), sh = std::fabs(src.height);
    float u0 = src.x / tw, u1 = (src.x + sw) / tw;
    float v0 = src.y / th, v1 = (src.y + sh) / th;
    if (flipX) { const float t2 = u0; u0 = u1; u1 = t2; }
    if (flipY) { const float t2 = v0; v0 = v1; v1 = t2; }

    // Corners relative to the origin point, rotated about it, placed at dst.x/y.
    const float dx = -origin.x, dy = -origin.y;
    Vector2 tl, tr, bl, br;
    if (rotationDeg == 0.0f) {
        tl = Vector2 {dst.x + dx, dst.y + dy};
        tr = Vector2 {tl.x + dst.width, tl.y};
        bl = Vector2 {tl.x, tl.y + dst.height};
        br = Vector2 {tl.x + dst.width, tl.y + dst.height};
    } else {
        const float rad = rotationDeg * kPi / 180.0f, s = std::sin(rad), c = std::cos(rad);
        const float x2 = dx + dst.width, y2 = dy + dst.height;
        tl = Vector2 {dst.x + dx * c - dy * s, dst.y + dx * s + dy * c};
        tr = Vector2 {dst.x + x2 * c - dy * s, dst.y + x2 * s + dy * c};
        bl = Vector2 {dst.x + dx * c - y2 * s, dst.y + dx * s + y2 * c};
        br = Vector2 {dst.x + x2 * c - y2 * s, dst.y + x2 * s + y2 * c};
    }
    const unsigned int p = Pack(tint);
    PushTriangle(tex, V(tl.x, tl.y, u0, v0, p), V(tr.x, tr.y, u1, v0, p), V(br.x, br.y, u1, v1, p));
    PushTriangle(tex, V(tl.x, tl.y, u0, v0, p), V(br.x, br.y, u1, v1, p), V(bl.x, bl.y, u0, v1, p));
}

void Rect(Rectangle r, Color c)
{
    Quad(g.white, Rectangle {0.0f, 0.0f, 1.0f, 1.0f}, r, Vector2 {0.0f, 0.0f}, 0.0f, c);
}

void RectGradientH(Rectangle r, Color left, Color right)
{
    const unsigned int l = Pack(left), rt = Pack(right);
    const float x1 = r.x + r.width, y1 = r.y + r.height;
    PushTriangle(g.white, V(r.x, r.y, 0.5f, 0.5f, l), V(x1, r.y, 0.5f, 0.5f, rt), V(x1, y1, 0.5f, 0.5f, rt));
    PushTriangle(g.white, V(r.x, r.y, 0.5f, 0.5f, l), V(x1, y1, 0.5f, 0.5f, rt), V(r.x, y1, 0.5f, 0.5f, l));
}

void RectLines(Rectangle r, float thick, Color c)
{
    assert(thick > 0.0f);
    Rect(Rectangle {r.x, r.y, r.width, thick}, c);
    Rect(Rectangle {r.x, r.y + r.height - thick, r.width, thick}, c);
    Rect(Rectangle {r.x, r.y + thick, thick, r.height - 2.0f * thick}, c);
    Rect(Rectangle {r.x + r.width - thick, r.y + thick, thick, r.height - 2.0f * thick}, c);
}

void Triangle(Vector2 a, Vector2 b, Vector2 c, Color col)
{
    PushSolid(a, b, c, col);
}

void Line(Vector2 a, Vector2 b, float thick, Color c)
{
    assert(thick > 0.0f);
    const float dx = b.x - a.x, dy = b.y - a.y;
    const float len = std::sqrt(dx * dx + dy * dy);
    if (len <= 0.0f) { return; }
    const float nx = -dy / len * thick * 0.5f, ny = dx / len * thick * 0.5f;
    PushSolid(Vector2 {a.x + nx, a.y + ny}, Vector2 {b.x + nx, b.y + ny}, Vector2 {b.x - nx, b.y - ny}, c);
    PushSolid(Vector2 {a.x + nx, a.y + ny}, Vector2 {b.x - nx, b.y - ny}, Vector2 {a.x - nx, a.y - ny}, c);
}

void CircleSector(Vector2 centre, float radius, float startDeg, float endDeg, int segments, Color c)
{
    assert(radius >= 0.0f);
    if (segments < 4) { segments = 4; }
    if (segments > 360) { segments = 360; }
    const float step = (endDeg - startDeg) / static_cast<float>(segments) * kPi / 180.0f;
    float ang = startDeg * kPi / 180.0f;
    for (int i = 0; i < segments; ++i) {
        const Vector2 p0 {centre.x + std::cos(ang) * radius, centre.y + std::sin(ang) * radius};
        const Vector2 p1 {centre.x + std::cos(ang + step) * radius, centre.y + std::sin(ang + step) * radius};
        PushSolid(centre, p0, p1, c);
        ang += step;
    }
}

void Circle(Vector2 centre, float radius, Color c)
{
    CircleSector(centre, radius, 0.0f, 360.0f, kCircleSegments, c);
}

void CircleLines(Vector2 centre, float radius, Color c)
{
    assert(radius >= 0.0f);
    const float step = 2.0f * kPi / static_cast<float>(kCircleSegments);
    for (int i = 0; i < kCircleSegments; ++i) {
        const float a0 = step * static_cast<float>(i), a1 = a0 + step;
        Line(Vector2 {centre.x + std::cos(a0) * radius, centre.y + std::sin(a0) * radius},
             Vector2 {centre.x + std::cos(a1) * radius, centre.y + std::sin(a1) * radius}, 1.0f, c);
    }
}

void Ellipse(Vector2 centre, float rx, float ry, Color c)
{
    assert(rx >= 0.0f && ry >= 0.0f);
    const float step = 2.0f * kPi / static_cast<float>(kCircleSegments);
    for (int i = 0; i < kCircleSegments; ++i) {
        const float a0 = step * static_cast<float>(i), a1 = a0 + step;
        PushSolid(centre, Vector2 {centre.x + std::cos(a0) * rx, centre.y + std::sin(a0) * ry},
                  Vector2 {centre.x + std::cos(a1) * rx, centre.y + std::sin(a1) * ry}, c);
    }
}

