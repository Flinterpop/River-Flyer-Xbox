void SetTextureWrap(TextureId id, Wrap w)
{
    if (!ValidTexture(id)) { return; }
    draw::Flush();
    Tex(id).wrap = w;
}

TargetId CreateTarget(int width, int height)
{
    assert(width > 0 && height > 0);
    int slot = -1;
    for (int i = 0; i < kMaxTargets && slot < 0; ++i) { if (!g.targets[static_cast<size_t>(i)].used) { slot = i; } }
    const int texSlot = FreeTextureSlot();
    if (slot < 0 || texSlot < 0) { log::Write(log::Level::Warning, "GFX: no free render target or texture slot"); return TargetId {}; }

    D3D11_TEXTURE2D_DESC td {};
    td.Width = static_cast<UINT>(width); td.Height = static_cast<UINT>(height);
    td.MipLevels = 1; td.ArraySize = 1;
    td.Format = DXGI_FORMAT_R8G8B8A8_UNORM; td.SampleDesc.Count = 1;
    td.Usage = D3D11_USAGE_DEFAULT;
    td.BindFlags = D3D11_BIND_RENDER_TARGET | D3D11_BIND_SHADER_RESOURCE;

    TextureSlot& t = g.textures[static_cast<size_t>(texSlot)];
    TargetSlot&  r = g.targets[static_cast<size_t>(slot)];
    HRESULT hr = g.device->CreateTexture2D(&td, nullptr, &t.tex);
    if (SUCCEEDED(hr)) { hr = g.device->CreateShaderResourceView(t.tex.Get(), nullptr, &t.srv); }
    if (SUCCEEDED(hr)) { hr = g.device->CreateRenderTargetView(t.tex.Get(), nullptr, &r.rtv); }
    if (FAILED(hr)) {
        log::Write(log::Level::Error, "GFX: render target %d x %d failed (0x%08lx)", width, height, hr);
        t = TextureSlot {}; r = TargetSlot {};
        return TargetId {};
    }
    t.w = width; t.h = height; t.used = true; t.isTarget = true; t.filter = Filter::Point; t.wrap = Wrap::Clamp;
    r.texture = TextureId {texSlot}; r.w = width; r.h = height; r.used = true;
    return TargetId {slot};
}

void DestroyTarget(TargetId id)
{
    if (!ValidTarget(id)) { return; }
    if (g.boundTarget.index == id.index) { EndTarget(); }
    TargetSlot& r = g.targets[static_cast<size_t>(id.index)];
    DestroyTexture(r.texture);
    r = TargetSlot {};
}

bool      TargetValid(TargetId id)   { return ValidTarget(id); }
TextureId TargetTexture(TargetId id) { return ValidTarget(id) ? g.targets[static_cast<size_t>(id.index)].texture : TextureId {}; }

void BeginTarget(TargetId id)
{
    assert(ValidTarget(id) && !g.boundTarget.Valid());
    if (!ValidTarget(id)) { return; }
    draw::Flush();
    const TargetSlot& r = g.targets[static_cast<size_t>(id.index)];
    SetCurrentTarget(r.rtv.Get(), r.w, r.h);
    g.boundTarget = id;
}

void EndTarget()
{
    if (!g.boundTarget.Valid()) { return; }
    draw::Flush();
    g.boundTarget = TargetId {};
    SetCurrentTarget(g.backRtv.Get(), g.backW, g.backH);
}

